from __future__ import annotations
import argparse, csv, math, re
from collections import defaultdict

MASS_PATTERNS = {
    2863: re.compile(r"(?:EMPTY_2863|2863)"),
    3108: re.compile(r"(?:DESIGN_3108|3108)"),
    3258: re.compile(r"(?:FULL_3258|3258)"),
}

def mean(xs):
    return sum(xs) / len(xs)

def pooled_rmse(case_rmses):
    return math.sqrt(mean([v*v for v in case_rmses]))

def main():
    ap = argparse.ArgumentParser(description="Aggregate O27R1 WA-RSBE results by vehicle mass")
    ap.add_argument('summary_csv', help='summary.csv generated by scripts/run_wa_rsbe.py')
    ap.add_argument('--out', default='mass_sensitivity_wa_rsbe.csv')
    args = ap.parse_args()

    groups = defaultdict(list)
    with open(args.summary_csv, newline='', encoding='utf-8-sig') as f:
        for row in csv.DictReader(f):
            cid = row['case_id']
            mass = next((m for m,p in MASS_PATTERNS.items() if p.search(cid)), None)
            if mass is not None:
                groups[mass].append(row)

    out_rows = []
    for mass in sorted(groups):
        g = groups[mass]
        out_rows.append({
            'Mass (kg)': mass,
            'Cases': len(g),
            'Slope RMSE (deg)': pooled_rmse([float(r['pitch_rmse_deg']) for r in g]),
            'Slope MAE (deg)': mean([float(r['pitch_mae_deg']) for r in g]),
            'Bank RMSE (deg)': pooled_rmse([float(r['bank_rmse_deg']) for r in g]),
            'Bank MAE (deg)': mean([float(r['bank_mae_deg']) for r in g]),
        })

    with open(args.out, 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.DictWriter(f, fieldnames=out_rows[0].keys())
        w.writeheader(); w.writerows(out_rows)
    for r in out_rows:
        print(r)

if __name__ == '__main__':
    main()
